def map_symbol(map_file: Path, name: str, required: bool = True):
    text = map_file.read_text(errors="replace")
    m = re.search(rf"^\s*([0-9A-F]{{6}})H\s+{re.escape(name)}\b", text, re.M)
    if not m:
        if not required:
            return None
        raise SystemExit(f"symbol not found in map: {name}")
    return int(m.group(1), 16)


def parse_ihex(path: Path) -> dict:
    upper = 0
    out = {}
    for raw in path.read_text(errors="replace").splitlines():
        line = raw.strip()
        if not line.startswith(":"):
            continue
        n = int(line[1:3], 16)
        addr = int(line[3:7], 16)
        typ = int(line[7:9], 16)
        body = line[9:9 + n * 2]
        if typ == 0:
            for i in range(n):
                out[upper + addr + i] = int(body[i * 2:i * 2 + 2], 16)
        elif typ == 2:
            upper = int(body, 16) << 4
        elif typ == 4:
            upper = int(body, 16) << 16
        elif typ == 1:
            break
    return out


def u16(img, off):
    return img[off] | (img[off + 1] << 8)


def u32(img, off):
    return (img[off] | (img[off + 1] << 8)
            | (img[off + 2] << 16) | (img[off + 3] << 24))


def put16(img, off, v):
    img[off] = v & 0xFF
    img[off + 1] = (v >> 8) & 0xFF


def put32(img, off, v):
    for i in range(4):
        img[off + i] = (v >> (8 * i)) & 0xFF


def bootsum_pages(img: bytes) -> list:
    """The page bases the RETAINED boot block will sample, DERIVED FROM THE
    IMAGE'S OWN HEADER rather than from a constant kept in step by hand.

    This mirrors boot-block 0x72D2-0x7380 exactly, and the mirror is checked by
    executing the real thing - tests/firmware/build/me711_bootsum_coverage_proof.py runs the
    Bosch routine in c167sim and requires the address sets to be identical.
    That is the whole reason this reads the header: the previous version
    hardcoded the two ranges, so moving the boundary would have changed what
    the ECU checks without changing what the build computes, and the stored
    record would have been wrong in exactly the way that costs an ECU.

      loop 1:  base = 0x800000 (hardcoded in the boot block)
               while base <  table+0x10     step 0x2000
      loop 2:  base = (table+0x14 & ~1) + 2
               while base <= header+0x14    step 0x2000
    """
    tbl = (u32(img, HEADER + 0x08) + 0x808000) - 0x800000   # -> file offset
    r1_limit = u32(img, tbl + 0x10) - 0x800000
    r2_start = ((u32(img, tbl + 0x14) & ~1) + 2) - 0x800000
    r2_limit = u32(img, HEADER + 0x14) - 0x800000
    pages = []
    base = 0x000000                       # boot block 0x7304: MOV R8,#0 R9,#0080h
    while base < r1_limit:
        pages.append(base); base += PAGE
    base = r2_start
    while base <= r2_limit:
        pages.append(base); base += PAGE
    return pages


def program_page_sum(img: bytes) -> int:
    """The 0x803C record: first + last word of every 8 KiB page the boot block
    samples. The page list comes from bootsum_pages(), which reads it out of
    this image's own ROMSYS header - see the BOOTSUM_* block above."""
    total = 0
    for base in bootsum_pages(img):
        total += u16(img, base) + u16(img, base + PAGE - 2)
    return total & 0xFFFFFFFF


def startup_sum(img: bytes) -> int:
    """The 0x8038 record: word[0x8000] + word[0xFFFE]."""
    return (u16(img, 0x8000) + u16(img, 0xFFFE)) & 0xFFFFFFFF


def relocate_vectors(img: bytearray, park: int, dest: int,
                     map_text: str = "") -> tuple:
    """Move Keil's parked vector table to where interrupts really land.

    Interrupts on this family are vectored twice. The C167's own table at flash
    0x000000 is inside the retained boot block; 105 of its 128 slots forward to
    seg82:N*4 == flash 0x020000 + N*4, and THAT is the table HaniCore owns.
    Keil is told to park VECTAB inside our own code sector; this copies it to
    `dest` and blanks the parked copy, so the finished image holds exactly one
    vector table and no stale second one to mislead the next reader.

    Slot 0 is the reset vector. It belongs to the boot block and is left alone.

    Every slot Keil did not fill gets a JMPS to its own assembly stub hc_vNN
    (gen_vector_probe.py, 2026-10-06: A166 allows one interrupt TASK per
    module, so the stubs are plain labels), or - if a slot has no stub - a
    copy of the catch-all handler's entry, so an interrupt nobody asked for is
    COUNTED rather than executing 0xFF.
    """
    tab = bytes(img[park:park + 0x200])
    if tab[0] != 0xFA:
        raise SystemExit(
            f"FATAL: no reset JMPS in the parked vector table at 0x{park:06X}. "
            "Check VECTAB() in the linker script and the OH166 RANGE.")
    template = tab[BADVEC_TRAP * 4: BADVEC_TRAP * 4 + 4]
    if template[0] != 0xFA:
        raise SystemExit(
            f"FATAL: no catch-all handler at trap 0x{BADVEC_TRAP:02X}. Run "
            "tools/build/gen_vector_probe.py me711.")
    if dest < CONTRACT_LEN and not (ISR_TABLE <= dest < CONTRACT_LEN):
        raise SystemExit("FATAL: vector table destination inside the boot block")

    # Slot 0 of the SECOND-level table. On the OEM image it self-loops; here
    # nothing reaches it, because the first-level reset slot goes straight to
    # the boot block's own stub. Filling it with the catch-all rather than
    # leaving it 0xFF costs four bytes and means every slot in this table is
    # a real instruction.
    img[dest:dest + 4] = template

    stubs = {int(m.group(2), 16): int(m.group(1), 16) for m in re.finditer(
        r"^\s*([0-9A-F]{6})H\s+hc_v([0-9A-F]{2})\s", map_text, re.M)}
    used, filled = [], 0
    for vec in range(4, 0x200, 4):
        e = tab[vec:vec + 4]
        if e == b"\xFF\xFF\xFF\xFF":
            a = stubs.get(vec // 4)
            e = (bytes((0xFA, a >> 16, a & 0xFF, (a >> 8) & 0xFF))
                 if a is not None else template)
            filled += 1
        elif vec != BADVEC_TRAP * 4:
            used.append((vec // 4, e[1], e[2] | (e[3] << 8)))
        img[dest + vec:dest + vec + 4] = e
    img[park:park + 0x200] = b"\xFF" * 0x200
    return used, filled, template


def first_level_map(contract: bytes) -> dict:
    """What the boot block's own vector table does with each trap. A HaniCore
    handler is only reachable for traps that forward to seg82:N*4."""
    out = {}
    for slot in range(128):
        e = contract[slot * 4: slot * 4 + 4]
        if e[0] != 0xFA:
            out[slot] = ("not a JMPS", None)
            continue
        seg, off = e[1], e[2] | (e[3] << 8)
        tgt = (seg << 16) | off
        if seg == 0x82 and off == slot * 4:
            out[slot] = ("forwards", tgt)
        elif seg == 0x82:
            out[slot] = ("forwards to a DIFFERENT slot", tgt)
        elif seg == 0x00:
            # Critical traps 2/4/6/10 enter a Bosch guard stub first.  With
            # E2BA==0x88 the stub's instruction at +12 forwards to this
            # trap's application slot; otherwise it executes SRST.  Treating
            # every segment-0 target as unreachable incorrectly reported the
            # physically observed V48 NMI handler as impossible.
            j = contract[off + 12:off + 16]
            if (len(j) == 4 and j[0] == 0xFA and j[1] == 0x82
                    and (j[2] | (j[3] << 8)) == slot * 4):
                out[slot] = ("conditional forwards", tgt)
            else:
                out[slot] = ("boot block", tgt)
        else:
            out[slot] = ("elsewhere", tgt)
    return out


