r"""
build_hanicore_me711.py - build the clean 1 MiB HaniCore image for the
Bosch ME7.1.1, hardware 0261207696 / project OEM ME7.1.1 / variant 44F.

    py tools\build\build_hanicore_me711.py

What "clean" means here, precisely
----------------------------------
NOT ONE BYTE of the Bosch engine application is in the output. 896 KiB of it -
everything from 0x020000 to 0x0FFFFF - is replaced by HaniCore code or by 0xFF.
The application entry pointer the boot block reads points at HaniCore's own
startup, so no OEM instruction is ever fetched.

What IS retained, and why, is one region and it is named honestly:

    0x000000-0x01FFFF   the external BOOT BLOCK and the parameter-page window

That is the reset path, not application code - see tools/build/me711_boot_contract.py
for the argument and an OEM-firmware analysis script (not published) for the machine-checked
evidence. It comes from a checked-in, hash-pinned blob, so this build does not
need an OEM read present at all.

Inside that region three things ARE generated by this script rather than
copied, which is what makes the boot contract HaniCore's:

    0x008000/0x008002   the application entry far pointer -> ?C_STARTUP
    0x008038            word[0x8000] + word[0xFFFE]
    0x00803C            the sum of the first and last word of every 8 KiB page
                        over 0x0000-0xFFFF and 0x20000-0xFFFFF

Those three are the ONLY checksums the boot path enforces. That is not an
assumption: the bench-proven ME7.5 HaniCore image satisfies exactly these three
and FAILS more than fifty of the application-layer multipoint checksums, and it
boots and runs. Application-layer checksums belong to an application that no
longer exists here, and are deliberately not maintained.

Nothing in here flashes anything.
"""
