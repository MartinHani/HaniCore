# ===========================================================================
# THE BOOT-ENFORCED PROGRAM-PAGE RECORD IS METADATA-DRIVEN, AND THIS IS THE
# METADATA. It is not a constant anybody chose here; it is read by the RETAINED
# Bosch boot block out of the ROMSYS header this file generates.
#
# The chain, disassembled out of binaries/original/an ME7 boot-sector read on 2026-09-13 and
# then MEASURED by executing it (tests/firmware/build/me711_bootsum_coverage_proof.py):
#
#   header+0x08 -> far pointer, +0x808000 -> the descriptor table, which the
#                  OEM puts at header+0x20;
#   table+0x10  -> E25A:E25C, loop 1's LIMIT     (loop 1 starts at 0x800000,
#                                                 and THAT is hardcoded at
#                                                 boot-block 0x7304-0x7306);
#   table+0x14  -> E25E:E260, (&~1)+2 = loop 2's START;
#   header+0x14 -> loop 2's LIMIT, read at boot-block 0x72D2 and NOWHERE ELSE.
#
# Each loop adds word[base] + word[base+0x1FFE] for every 8 KiB page and
# strides 0x2000, which is why a cell body must start at page+2 and stop
# before page+0x1FFE.
#
# WHY THE LIMIT MOVED, V53. An AMD embedded erase PRE-PROGRAMS the whole sector
# to 0x00 before erasing it, so for the ~2 s an erase takes, every sampled word
# in that sector is wrong. The board ties the 29F800's RESET pin (44-pin SO
# pin 44) to RSTIN_FR, so SWRST_SM ABORTS an erase and leaves the sector
# indeterminate - and a sampled word that is not 0xFFFF means the boot block
# refuses to enter HaniCore, which is physically proven
# (the maintainer's design records). While the store was inside
# this record, reclaiming it could brick the ECU to bootmode.
#
# So the persistence store was moved ABOVE the limit instead. Bosch already
# does exactly this for the parameter page: SA4 sits in the HOLE between the
# two loops and carries its own two-word record. This is that pattern, applied
# to storage that is genuinely mutable.
#
# EVERY EXECUTABLE BYTE IS STILL COVERED. The loop offers two ranges, so the
# excluded region has to be contiguous at the top - which is why HaniCore's
# code moved from SA17 down to SA7.
