#!/usr/bin/env python3
r"""
hcconfig_layout.py - parse the FIRMWARE's own calibration page layout out of
firmware/config/hcconfig.h.

    py tools\config_source\hcconfig_layout.py

WHY THIS IS THE AUTHORITY AND THE PYTHON MODEL IS NOT.

hcconfig.h defines the 4096-byte TunerStudio constants page that the SHIPPING
firmware actually reads and writes. Its offsets are baked into every image ever
flashed, into the frozen V26 bench bundle, and into every .ini generated by
tools/tunerstudio/gen_ts_ini_me711.py. A second, incompatible 4096-byte layout - which is
exactly what tools/config_source/hanicore_config_def.py first introduced, with
cylinderCount at offset 9 where hcconfig.h has CFG_CYLINDERS at 2 - is not a
source of truth, it is a way to write a cylinder count into a page-size field.

So the direction of authority is:

    hcconfig.h  ->  this parser  ->  the Python model's frozen offsets
                                       |
                                       +-> generated C offsets
                                       +-> generated TunerStudio [Constants]

and generate_config.py FAILS if the model and hcconfig.h disagree by one byte.
New universal fields are allowed only in hcconfig.h's own reserved region
(CAL_RESERVED .. HC_CFG_SIZE-1), and adding one means editing hcconfig.h too.

The parse is deliberately literal: `#define NAME <offset> /* <type> ... */`.
The type comes out of the comment because that is where hcconfig.h writes it,
and the file's own convention - "u8 = one byte, u16 = two bytes big-endian" -
is stated at the top of its layout section.
"""
from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HCCONFIG_H = ROOT / "firmware/config/hcconfig.h"

# "#define CAL_FUEL_MAP 128 /* u8[256] injection us / 32 */"
_DEF = re.compile(
    r"^#define\s+(?P<name>(?:CFG|CAL)_[A-Z0-9_]+)\s+(?P<off>\d+)\s*(?:/\*(?P<cmt>.*?)\*/)?\s*$"
)
# "u16[8]" / "u8" / "u16"
_TYPE = re.compile(r"\b(?P<t>u8|u16|s16)(?:\[(?P<n>\d+)\])?")

_SIZE = {"u8": 1, "u16": 2, "s16": 2}

# CFG_/CAL_ defines in hcconfig.h that are NOT page offsets. Listed by name on
# purpose: anything else without a type comment is an error, not a skip, so a
# new layout field cannot be silently dropped from the model.
NON_LAYOUT = {
    # markers for a deliberately unowned range
    "CFG_RESERVED", "CAL_RESERVED",
    # table geometry
    "CAL_AXIS_N", "CAL_MAP_N",
    # hc_cfg_faults() bit mask
    "CFG_FAULT_CYLINDERS", "CFG_FAULT_STROKES", "CFG_FAULT_TEETH",
    "CFG_FAULT_TDC_RANGE", "CFG_FAULT_TDC_DUP", "CFG_FAULT_CHANNEL",
    "CFG_FAULT_REV", "CFG_FAULT_VERSION",
    # sentinel and enumeration values
    "CAL_IAT_NONE", "CAL_LOAD_MAP", "CAL_LOAD_TPS", "CAL_LOAD_ALPHAN",
    "CAL_TEMP_BIAS",
    # the universal block's own size, stated beside its base
    "CFG_UNIVERSAL_SIZE",
}


@dataclass(frozen=True)
class Slot:
    name: str
    offset: int
    ctype: str          # u8 | u16 | s16
    count: int
    comment: str

    @property
    def size(self) -> int:
        return _SIZE[self.ctype] * self.count

    @property
    def end(self) -> int:
        """First byte AFTER this slot."""
        return self.offset + self.size


def constant(text: str, name: str) -> int:
    m = re.search(r"#define\s+%s\s+(0x[0-9A-Fa-f]+|\d+)" % name, text)
    if not m:
        raise SystemExit("%s not found in hcconfig.h" % name)
    return int(m.group(1), 0)


def parse(path: Path = HCCONFIG_H) -> tuple[list[Slot], dict[str, int]]:
    text = path.read_text(errors="replace")
    consts = {
        "HC_CFG_SIZE": constant(text, "HC_CFG_SIZE"),
        "HC_CFG_CORE": constant(text, "HC_CFG_CORE"),
        "HC_MAX_CYL": constant(text, "HC_MAX_CYL"),
        "HC_CFG_VERSION": constant(text, "HC_CFG_VERSION"),
        "CAL_AXIS_N": constant(text, "CAL_AXIS_N"),
    }
    slots: list[Slot] = []
    for line in text.splitlines():
        m = _DEF.match(line.strip())
        if not m:
            continue
        name = m.group("name")
        if name in NON_LAYOUT:
            continue
        cmt = (m.group("cmt") or "").strip()
        tm = _TYPE.search(cmt)
        if not tm:
            # A layout define with no type in its comment is a bug in
            # hcconfig.h, not something to guess at.
            raise SystemExit(
                "hcconfig.h: %s has no u8/u16/s16 in its comment - the layout "
                "cannot be derived from it. Fix the comment; do not guess." % name)
        slots.append(Slot(name, int(m.group("off")), tm.group("t"),
                          int(tm.group("n") or 1), cmt))
    slots.sort(key=lambda s: s.offset)
    return slots, consts


def audit(slots: list[Slot], consts: dict[str, int]) -> list[str]:
    """Overlap / alignment / bounds problems in the FIRMWARE's own layout."""
    problems: list[str] = []
    owner: dict[int, str] = {}
    for s in slots:
        if s.ctype in ("u16", "s16") and s.offset % 2:
            problems.append("MISALIGNED %s at %d (%s wants an even offset)"
                            % (s.name, s.offset, s.ctype))
        if s.end > consts["HC_CFG_SIZE"]:
            problems.append("PAST END %s ends at %d, page is %d"
                            % (s.name, s.end, consts["HC_CFG_SIZE"]))
        for b in range(s.offset, min(s.end, consts["HC_CFG_SIZE"])):
            if b in owner:
                problems.append("OVERLAP byte %d: %s and %s" % (b, owner[b], s.name))
            else:
                owner[b] = s.name
    return problems


def holes(slots: list[Slot], upto: int) -> list[tuple[int, int]]:
    """Unowned byte ranges below `upto`, as (first, last) inclusive."""
    out: list[tuple[int, int]] = []
    cursor = 0
    for s in slots:
        if s.offset > cursor:
            out.append((cursor, s.offset - 1))
        cursor = max(cursor, s.end)
    if cursor < upto:
        out.append((cursor, upto - 1))
    return out


def main() -> int:
    slots, consts = parse()
    print("hcconfig.h: %d layout slots, page %d bytes, core %d bytes, HC_MAX_CYL %d"
          % (len(slots), consts["HC_CFG_SIZE"], consts["HC_CFG_CORE"], consts["HC_MAX_CYL"]))
    top = max(s.end for s in slots)
    print("highest byte in use: %d  (reserved tail %d..%d = %d bytes)"
          % (top - 1, top, consts["HC_CFG_SIZE"] - 1, consts["HC_CFG_SIZE"] - top))
    problems = audit(slots, consts)
    if problems:
        print("PROBLEMS:")
        for p in problems:
            print("   " + p)
    else:
        print("no overlaps, no misalignment, nothing past the end of the page")
    hs = [h for h in holes(slots, top) if h[0] <= h[1]]
    print("interior holes (unowned bytes below the top of use): %d, %d bytes"
          % (len(hs), sum(b - a + 1 for a, b in hs)))
    for a, b in hs:
        print("   %d..%d (%d)" % (a, b, b - a + 1))
    if "--list" in sys.argv:
        for s in slots:
            print("  %-24s %5d %-6s x%-4d %4d B  %s"
                  % (s.name, s.offset, s.ctype, s.count, s.size, s.comment[:50]))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
