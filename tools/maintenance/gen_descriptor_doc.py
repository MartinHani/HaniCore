#!/usr/bin/env python3
r"""
gen_descriptor_doc.py - write docs/PINOUT.md from the hardware
descriptor the firmware's pin table is generated from.

    py tools\maintenance\gen_descriptor_doc.py           write it
    py tools\maintenance\gen_descriptor_doc.py --check   exit 1 if it is stale

The descriptor (tools/config_source/hw_descriptors.py) is the one source of
truth for what each cavity can do; this page is its readable dump, so the
documentation cannot drift from what the validator accepts.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "lib"))
import hcpaths  # noqa: F401,E402
import hw_descriptors as HW  # noqa: E402

OUT = ROOT / "docs" / "PINOUT.md"


def render() -> str:
    d = HW.build_me711()
    rows = []
    for p in d.pins:
        mask = 0
        for pp in p.properties:
            mask |= pp.cap
        caps = HW.cap_names(mask) if p.properties else "-"
        ev = ", ".join(sorted({pp.evidence.name for pp in p.properties})) or "-"
        friendly = HW.FRIENDLY_CAVITY_NAMES.get(p.number, "")
        meaning = (p.meaning or "").replace("|", "/").replace("\n", " ")
        if len(meaning) > 110:
            meaning = meaning[:107] + "..."
        rows.append("| %d | %s | `%s` | %s | %s | %s | %s |" % (
            p.number, friendly, (p.oem_name or "").replace("|", " / "), caps.replace("|", ", "),
            ev, (p.hal_resource or "").replace("|", "/"), meaning))
    head = [
        "# ME7.1.1 connector pinout (generated)",
        "",
        "<!-- GENERATED by tools/maintenance/gen_descriptor_doc.py from",
        "     tools/config_source/hw_descriptors.py. Do not edit. -->",
        "",
        "Every cavity of the Porsche ME7.1.1 connector as the firmware's pin table",
        "sees it: the label TunerStudio shows, the Bosch net name, the capabilities",
        "the validator allows, the evidence class of those capabilities, the CPU/ASIC",
        "resource, and the meaning. `SPECIAL_LOCKED` cavities are never routable.",
        "**PROBABLE** = Bosch documentation for this family, not measured on this board;",
        "**VERIFIED** = measured or settled by agreeing primary sources. The",
        "hardware behind it is described in [PLATFORM.md](PLATFORM.md); per-capability",
        "sources are in `tools/config_source/hw_descriptors.py`.",
        "",
        "| cavity | TunerStudio label | Bosch net | capabilities | evidence | resource | meaning |",
        "|---|---|---|---|---|---|---|",
    ]
    return "\n".join(head + rows) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        ok = cur == text
        print("[%s] %s is %s" % ("PASS" if ok else "FAIL", OUT.relative_to(ROOT).as_posix(),
                                 "current" if ok else "STALE - run without --check"))
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
