#!/usr/bin/env python3
r"""
me711_och_contract_proof.py - the firmware's ACTUAL runtime reply size against
the .ini that tells TunerStudio what to expect.

    py tests\tunerstudio\me711_och_contract_proof.py
    py tests\tunerstudio\me711_och_contract_proof.py --ini <path> --image <path>

WHY THIS EXISTS: A PHYSICAL FAILURE, ON HARDWARE, 2026-09-02.

The frozen V29 physical-test image was flashed to the real Cayenne ECU. It
connected, answered its signature, and read the calibration page. Then
TunerStudio oscillated Online/Offline about once a second, deterministically,
and its log said the same thing every time:

    Unexpected runtime response size, expected: 116, received: 112

Those two numbers are not arbitrary and they are not a baud problem, a
watchdog reset or a traffic-load problem. They are arithmetic:

    blockingFactor = 256, so TunerStudio reads the output-channel block in
    chunks of at most 256 bytes. The LAST chunk is ochBlockSize - 256.

        the .ini that was loaded said ochBlockSize = 372  ->  372 - 256 = 116
        the image that was flashed had TGT_OCH_SIZE = 368 ->  368 - 256 = 112

hcts.c clamps: `if (cnt > TGT_OCH_SIZE - off) cnt = TGT_OCH_SIZE - off;`. So
the ECU answered 112 bytes to a request for 116, TunerStudio saw a short read,
and dropped the connection. Every reconnect repeated it.

THE DRIFT IS DATED. TGT_OCH_SIZE went 336 -> 368 (73e3a84) -> 372 (ad722ac,
"fix(v30): the VE table must not still be called a fuel map"). V29 was frozen
at 6107efa, BETWEEN those last two, so the frozen package is internally
consistent at 368/368 - and `tunerstudio/hanicore_me711.ini`, which is
regenerated by every build, moved on to 372. A bench that flashes the frozen
binary and opens the repo's live .ini gets 368 firmware and a 372 contract.

So this is not "the .ini is wrong" or "the firmware is wrong". It is that
NOTHING PINNED A BINARY TO ITS .INI, exactly as nothing pinned a gate to its
image before tools/lib/me711_image.py, and exactly as nothing pinned the ME7.5
image to its source before tools/me75_image.py. Same defect, third surface.

WHY THE EXISTING GATES DID NOT CATCH IT.

`ts_ini_check.py` and `check_hanicore_ts_ini_syntax.py` both read the SAME
`hctarget.h` the .ini was generated from, so they compare a number with itself
and agree by construction. They can never see this: the mismatch only exists
between a BUILT BINARY and a SEPARATELY GENERATED .ini, and neither gate loads
a binary at all.

This one does. It EXECUTES the linked image in c167sim, sends the exact
`O`-command TunerStudio would send for the last chunk given the .ini's own
ochBlockSize and blockingFactor, and counts the payload bytes that come back.
That is the measurement the bench made, made offline.
"""
from __future__ import annotations

import argparse
import binascii
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools" / "lib"))
import hcpaths  # noqa: F401,E402  (puts every tools/ and tests/ module on sys.path)

import me711_burn_session_proof as BS     # noqa: E402  the frame decoder
import me711_heartbeat_gap_proof as HB   # noqa: E402  the Rig
import me711_image as PI                 # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
LIVE_INI = ROOT / "tunerstudio/hanicore_me711.ini"

FAILS = 0
CHECKS = 0


def check(name, ok, detail=""):
    global FAILS, CHECKS
    CHECKS += 1
    print("  [%s] %-56s %s" % ("PASS" if ok else "FAIL", name, detail))
    if not ok:
        FAILS += 1


def ini_numbers(path: Path):
    """(ochBlockSize, blockingFactor, signature) out of a TunerStudio .ini."""
    t = path.read_text(errors="replace")

    def num(key):
        m = re.search(r"^\s*%s\s*=\s*(\d+)" % key, t, re.M)
        if not m:
            raise SystemExit("%s not found in %s" % (key, path.name))
        return int(m.group(1))

    sig = re.search(r'^\s*signature\s*=\s*"([^"]*)"', t, re.M)
    return num("ochBlockSize"), num("blockingFactor"), sig.group(1) if sig else ""


envelope = HB.envelope      # one definition: 16-bit length (see HB)


def och_request(off: int, cnt: int) -> bytes:
    """The exact bytes ochGetCommand = "O%2o%2c" produces."""
    return envelope(b"O" + off.to_bytes(2, "big") + cnt.to_bytes(2, "big"))


# HOW LONG BOOT TAKES, MEASURED FOR THE SELECTED IMAGE RATHER THAN ASSUMED.
#
# This gate injected its request at step 750 000 and ran for 2 200 000, both
# of which predate V39's append-only calibration store. That store is scanned
# before the supervision link comes up - sixteen cells, and a blank one has
# its whole 8188-byte body read - which is 1.19M instructions on its own, so
# the first ASIC exchange of this image is at step 2 482 756. The request was
# being handed to an ECU that was still booting and the run ended before it
# could answer: "no valid envelope in the transmitted stream" was a true
# statement about a question nobody had asked yet.
#
# me711_boot_cost_proof is the gate that OWNS that number and reports it; this
# one only has to inject after it.
BOOT_STEPS = PI.BOOT_STEPS
SETTLE_STEPS = 750_000


# THE BUDGET FOLLOWS THE REPLY, BECAUSE A LITERAL ONE WAS SILENTLY MARGINAL.
#
# `ask()` used a flat 1 500 000 steps. TGT_OCH_READ_SIZE on this target is
# 1024 - the forensic extended view, NOT TGT_OCH_SIZE - so asking 0xFFFF gets
# a 1031-byte reply, and hcts_tx() is baud-paced and blocking, so the step cost
# is proportional to the bytes. 1 500 000 sat just inside what V54 needed and
# just outside what V55 needed, and V55 is only 2-3 % dearer per byte: measured
# 703/729/1031 bytes out of both images with last-byte timestamps within 4 %.
#
# So the gate reported "no valid envelope in the transmitted stream" - a true
# statement about a reply that had not finished yet - and it read exactly like
# a firmware defect. It is the same failure this file's own BOOT_STEPS comment
# describes, one layer further along.
STEPS_PER_REPLY_BYTE = 4_000
STEPS_FLOOR = 1_500_000


def ask(image: Path, off: int, cnt: int, steps: int | None = None,
        request: bytes | None = None):
    """Send one O request to the linked image; return the reply PAYLOAD length.

    The reply is `code` + payload + 4 CRC bytes inside a 2-byte length
    envelope, so the payload length is what TunerStudio counts and what its
    error message reports.
    """
    rig = HB.Rig(image, HB.ENTRY_CURRENT, HB.TICK_CURRENT, echo=False)
    # Reach known steady runtime first.  An absolute injection step silently
    # loses the request if a larger image is still inside hcts_init(), which
    # clears the receive ring.  Rig.run() is explicitly incremental, so queue
    # relative to the CPU state that has actually reached the settled window.
    rig.run(BOOT_STEPS + SETTLE_STEPS)
    rig.queue_rx(rig.cpu.steps + 1, request or och_request(off, cnt))
    if steps is None:
        want = min(cnt, 4096) + 8
        steps = max(STEPS_FLOOR, want * STEPS_PER_REPLY_BYTE)
    rig.run(steps)
    tx = bytes(b for _t, b in rig.tx)
    # The boot banner precedes the reply and is not enveloped. Find the last
    # well-formed envelope in the stream rather than assuming an offset.
    best, best_at_end = None, False
    for i in range(len(tx) - 1):
        n = (tx[i] << 8) | tx[i + 1]
        # The response body is status + OCH bytes.  The old 600-byte parser
        # ceiling predated the 680-byte contract and rejected the valid
        # 681-byte body before checking its CRC, reporting "no envelope".
        if 1 <= n <= 4097 and i + 2 + n + 4 <= len(tx):
            body = tx[i + 2:i + 2 + n]
            crc = int.from_bytes(tx[i + 2 + n:i + 6 + n], "big")
            if crc == (binascii.crc32(body) & 0xFFFFFFFF):
                # THE REPLY IS THE LAST THING SENT: an envelope that ends at
                # the end of the stream is it. 2026-10-15: the payload at 768
                # carried 00 01 ff ff 00 00 00 - a valid 1-byte envelope INSIDE
                # the real one - and "the last well-formed envelope" read 0.
                if best is None or i + 6 + n == len(tx) or not best_at_end:
                    best = body
                    best_at_end = i + 6 + n == len(tx)
    if best is None:
        return None, tx
    # body[0] is the response code; the rest is the payload.
    return len(best) - 1, tx


def firmware_och_size(image: Path):
    """The block size the image really publishes, MEASURED not read.

    Ask for far more than any plausible block from offset 0. hcts.c clamps the
    count to TGT_OCH_SIZE - off, so the reply length IS the block size.
    """
    n, _ = ask(image, 0, 0xFFFF)
    return n


# V93: THE BARE 'O' REPLY IS A WHOLE BLOCK, SO ITS BUDGET MUST BE ONE TOO.
# ask() sizes the budget from `cnt`, and the bare request carries none, so it
# ran on the 1.5 M floor - enough for V92's 824 bytes, not for V93's 864 with
# the scheduler now serviced on every transmitted byte (hcts_target_yield):
# the reply outlived the budget and read "normal None", the exact marginal-
# literal failure the comment above records. Budget the largest block this
# target has ever published plus margin.
BARE_O_BUDGET_BYTES = 1600


def firmware_normal_och_size(image: Path):
    """Measure the backward-compatible bare-O response used as normal OCH."""
    n, _ = ask(image, 0, 0, request=envelope(b"O"),
               steps=BARE_O_BUDGET_BYTES * STEPS_PER_REPLY_BYTE)
    return n


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ini", type=Path, default=LIVE_INI)
    ap.add_argument("--image", type=Path, default=None)
    ap.add_argument("--expect-mismatch", action="store_true",
                    help="invert the verdict: used by the mutation test to "
                         "prove this gate can actually fail")
    a = ap.parse_args()

    image = a.image or PI.image()
    print("=== HaniCore - the runtime (OCH) contract, measured ===\n")
    print("  image   %s" % image.name)
    print("  ini     %s" % a.ini.name)

    och_ini, blocking, sig = ini_numbers(a.ini)
    print("  ini says   ochBlockSize %d, blockingFactor %d, signature %r\n"
          % (och_ini, blocking, sig))

    # ---------------------------------------------------------------- 1
    fw = firmware_och_size(image)
    if fw is None:
        check("the image answers an O request at all", False,
              "no valid envelope in the transmitted stream")
        print("\n%d/%d checks pass" % (CHECKS - FAILS, CHECKS))
        return 1
    check("the image answers an O request", True, "%d-byte payload" % fw)
    normal_fw = firmware_normal_och_size(image)
    print("     FIRMWARE NORMAL BLOCK: %s bytes; MAX READ-ONLY VIEW: %d bytes"
          % (normal_fw, fw))

    # ---------------------------------------------------------------- 2
    # V49 deliberately has two contracts: a 680-byte normal block and a
    # bounded 1024-byte post-event forensic view.  Both are linked behavior,
    # measured independently here.  Older images have one equal size.
    ini_matches = och_ini in (normal_fw, fw)
    check("the .ini's ochBlockSize matches a linked firmware view",
          ini_matches,
          "ini %d vs normal %s / max %d%s" % (och_ini, normal_fw, fw,
                                       "" if ini_matches
                                       else "   <-- THIS IS THE BENCH FAILURE"))

    # ------------------------------------------------- 3: the real chunks
    #
    # This is the part that reproduces the hardware symptom rather than
    # inferring it. TunerStudio splits ochBlockSize into blockingFactor-sized
    # requests; every one of them must come back with exactly what was asked.
    print("\n  --- the chunks TunerStudio actually requests ---")
    off = 0
    while off < och_ini:
        cnt = min(blocking, och_ini - off)
        got, _ = ask(image, off, cnt)
        check("O offset %3d count %3d" % (off, cnt), got == cnt,
              "received %s%s" % (got,
                                 "" if got == cnt
                                 else "   <-- TunerStudio: 'Unexpected runtime "
                                      "response size, expected: %d, received: "
                                      "%d'" % (cnt, got)))
        off += cnt

    # ---------------------------------------------------- 4: the identity
    #
    # The bench also reported the ECU identifying itself as
    # "HaniCore V28 TRIGGER COMM" while running the V29 image. A version
    # string that names a different build than the binary is the same class of
    # defect as an .ini that names a different block size: it makes a bench log
    # unusable as evidence about which artefact was under test.
    print("\n  --- the identity the ECU reports ---")
    rig = HB.Rig(image, HB.ENTRY_CURRENT, HB.TICK_CURRENT, echo=False)
    # 'V' is the version; 'S' and 'Q' are the SIGNATURE, which is a
    # different string and does not carry the build number.
    rig.run(BOOT_STEPS + SETTLE_STEPS)
    rig.queue_rx(rig.cpu.steps + 1, envelope(b"V"))
    rig.run(1_000_000)
    tx = bytes(b for _t, b in rig.tx)
    # THE IDENTITY COMES OUT OF THE REPLY PAYLOAD, NOT A REGEX OVER THE WIRE.
    #
    # `HaniCore[ -~]{0,60}` is greedy over printable ASCII, and the version
    # string is NUL-terminated in the IMAGE but not on the WIRE: the reply is
    # `00 <len> | 00 <version> | crc32`, so the match ran off the end of the
    # payload into the CRC and appended any CRC byte that happened to be
    # printable. Measured on V74 - the payload's CRC32 is `39 a7 01 8a`, and
    # the gate reported `Bosch ME7.1.19`, where the 9 IS 0x39.
    #
    # The check below is a SUBSTRING test, so it PASSED while printing a build
    # identity that is not in the image - which is precisely the defect the
    # comment above says this section exists to catch, committed by the
    # instrument rather than the firmware.
    #
    # So decode the frame instead, with the one decoder that already defines
    # this wire format - the same rule that fixed its 8-bit length field.
    ident = "(none seen)"
    for _at, _end, payload in BS.frames(tx):
        m = re.search(rb"HaniCore[ -~]*", payload)
        if m:
            ident = m.group(0).decode("ascii", "replace")
            break
    print("     %s" % ident)
    stem = image.stem.lower()
    ver = re.search(r"v(\d+)", stem)
    check("the reported identity names the build in the filename",
          bool(ver) and ("v%s" % ver.group(1)) in ident.lower().replace(" ", ""),
          "image %r says %r" % (image.stem, ident))

    print("\n%d/%d checks pass" % (CHECKS - FAILS, CHECKS))
    if a.expect_mismatch:
        # The mutation mode: this gate is only worth anything if a mismatched
        # pair actually fails it.
        if FAILS:
            print("MUTATION OK - a mismatched image/.ini pair DOES fail this gate.")
            return 0
        print("MUTATION FAILED - a mismatched pair passed. The gate is vacuous.")
        return 1
    if FAILS:
        print("OCH CONTRACT MISMATCH - TunerStudio will drop and reconnect "
              "forever. This is the V29 bench failure of 2026-09-02.")
        return 1
    print("OCH CONTRACT PROOF PASSES - the firmware's runtime block and the "
          ".ini agree, measured out of the linked image.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
