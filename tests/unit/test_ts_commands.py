"""Every command TunerStudio can send must exist in the firmware.

A button in a tuning application that does nothing is worse than a missing one,
because a bench operator presses it and uses the absence of a result to rule
something out. That is exactly what happened here: the .ini offered "Stop the
alive text" and "Start the alive text", wired to '!Z' and '!z', which set a
flag called `alive_on`. Nothing had read that flag since V23 removed banner()
and step_line(), so both buttons were inert for six releases.

These tests close the loop in both directions:

  - every '!' command the generated .ini offers is handled by
    hcts_target_cmd();
  - every command hcts_target_cmd() handles is either offered by the .ini or
    listed here as deliberately terminal-only, with a reason.

They read the GENERATOR as well as its output, so a command added to the .ini
by hand - which would be overwritten on the next generate - is also caught.
"""
import re
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools" / "lib"))
import hcpaths  # noqa: F401,E402  (puts every tools/ and tests/ module on sys.path)

ROOT = Path(__file__).resolve().parents[2]
INI = ROOT / "tunerstudio/hanicore_me711.ini"
GEN = ROOT / "tools/tunerstudio/gen_ts_ini_me711.py"
MAIN = ROOT / "firmware/targets/me711/diagnostics/hcdiag711.c"

# Commands the firmware implements that the .ini deliberately does not offer.
# An entry needs a reason, not just a name.
TERMINAL_ONLY = {}


def _firmware_commands():
    """The subcommand letters hcts_target_cmd() actually handles."""
    src = MAIN.read_text(errors="replace")
    start = src.index("void far hc_target_cmd_cold(")
    end = src.index("\n}", start)
    body = src[start:end]
    # strip comments so a letter mentioned in prose is not counted
    body = re.sub(r"/\*.*?\*/", " ", body, flags=re.S)
    return set(re.findall(r"case\s+'(.)'\s*:", body))


def _ini_commands(text):
    """The subcommand letters the .ini can send, DECODED THE WAY TUNERSTUDIO
    DECODES THEM.

    ONLY [ControllerCommands] IS SCANNED, and that is a tightening rather than
    a loosening. A command can be declared nowhere else, while `field = "! red
    text"` is TunerStudio's documented way of writing a warning in red - and
    the dialog that can energise a throttle motor has several. Scanning the
    whole file counted those warnings as commands named '! ' and failed on
    them, which would have pushed the safety text off the dialog to keep a
    test green.

    THIS FUNCTION READ A BACKSLASH AS THE COMMAND LETTER FOR A WHOLE
    RELEASE. V37B respelled every literal as hex escapes - `"!\x4d\x11"`
    rather than `"!M\x11"` - because real TunerStudio drops a second
    consecutive plain character and that had left all 36 buttons inert. The old
    `= "!(.)` with a raw next character then captured a backslash, and every
    assertion in this file has been
    about that character since. The comparison against the generator failed to
    catch it because BOTH SIDES broke the same way.

    So the decoding is not done here. tests/tunerstudio/ts_ini_command_shape_proof.py
    builds it from the rusEFI corpus - 4553 literals in files known to load -
    and the project rules say so: a gate that models both halves of
    an interface from the same assumption tests nothing about the assumption.
    """
    import sys as _sys
    _sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
    import ts_ini_command_shape_proof as SHAPE

    out = set()
    body = text
    if "[ControllerCommands]" in body:
        body = body.split("[ControllerCommands]", 1)[1]
        nxt = re.search(r"^\[", body, re.M)
        if nxt:
            body = body[:nxt.start()]
    for m in re.finditer(r'=\s*"(![^"]*)"', body):
        wire, _subs = SHAPE.wire_bytes(m.group(1))
        # wire[0] is '!' itself; wire[1] is what hcts_target_cmd() switches on.
        if len(wire) >= 2:
            out.add(chr(wire[1]))
    return out


def test_the_ini_is_generated_and_says_so():
    assert INI.exists(), "the ME7.1.1 .ini has not been generated"
    head = INI.read_text(errors="replace")[:400]
    assert "GENERATED by" in head, (
        "the .ini does not declare its generator - a hand-edited .ini is lost "
        "on the next generate")


def test_every_ini_command_exists_in_the_firmware():
    fw = _firmware_commands()
    ini = _ini_commands(INI.read_text(errors="replace"))
    assert ini, "no '!' commands found in the .ini - the parser is wrong"
    missing = sorted(ini - fw)
    assert not missing, (
        "the .ini offers %s, which hcts_target_cmd() does not handle - those "
        "buttons would do nothing" % ", ".join("'!%s'" % c for c in missing))


def test_every_firmware_command_is_offered_or_declared_terminal_only():
    fw = _firmware_commands()
    ini = _ini_commands(INI.read_text(errors="replace"))
    unoffered = sorted(fw - ini - set(TERMINAL_ONLY))
    assert not unoffered, (
        "hcts_target_cmd() handles %s but nothing offers it and it is not in "
        "TERMINAL_ONLY - either expose it or say why not"
        % ", ".join("'!%s'" % c for c in unoffered))


def test_the_generator_agrees_with_its_own_output():
    """A command added to the .ini by hand disappears on the next generate.

    THIS USED TO SCAN THE GENERATOR'S PYTHON SOURCE for command literals, and
    there have been none there since V37B replaced 36 hand-written lines with
    one `cmd()` helper that formats them - it had to, because every subcommand
    letter became a hex escape. The scan then found the `%` of a format string
    and failed for a reason unrelated to hand editing.

    Scanning source text for what a program EMITS was the weak form of this
    check anyway. Run the generator and require the file not to move: that
    catches a hand edit anywhere in the file, not only in the command block.
    """
    import subprocess
    import sys

    before = INI.read_bytes()
    r = subprocess.run([sys.executable, str(GEN)], capture_output=True,
                       text=True, cwd=str(ROOT))
    assert r.returncode == 0, "the generator does not run:\n%s" % r.stderr[-2000:]
    after = INI.read_bytes()
    assert before == after, (
        "regenerating changed %s - it has been hand-edited, and the edit is "
        "lost on every build" % INI.name)


def test_the_dead_alive_text_buttons_are_gone():
    """The specific regression these tests were written for."""
    text = INI.read_text(errors="replace")
    assert "alive text" not in text.lower()
    assert "cmdAliveOn" not in text and "cmdAliveOff" not in text
    # Strip comments: the source explains the removal, and naming a thing in
    # prose is not reintroducing it.
    src = re.sub(r"/\*.*?\*/", " ",
                 MAIN.read_text(errors="replace"), flags=re.S)
    assert "alive_on" not in src, (
        "alive_on is back in the CODE - it is a flag nothing reads, and the "
        ".ini will grow buttons for it again")


def test_the_s5500_window_sweep_is_reachable_from_tunerstudio():
    """The one diagnostic that can close the runtime-frame analog mapping
    WITHOUT another flash. It was implemented in the firmware but reachable
    only from a terminal, which meant a bench session had to leave TunerStudio
    to use it."""
    text = INI.read_text(errors="replace")
    # THE LETTER IS AN ESCAPE NOW. V37B respelled every literal because real
    # TunerStudio drops a second consecutive plain character, so `"!W\x0c"`
    # became `"!\x57\x0c"` and the wire bytes stayed identical. Matching the
    # old spelling would fail against the file that actually works.
    assert re.search(r'"!(?:W|\\x57)', text), (
        "the '!W' window sweep is not offered")
    buttons = re.findall(
        r'cmdS5500Win(\d+)\s*=\s*"!(?:W|\\x57)\\x([0-9a-f]{2})"', text)
    assert len(buttons) >= 4, "too few sweep positions to cover the frame"
    for dec, hexbase in buttons:
        assert int(dec) == int(hexbase, 16), (
            "button cmdS5500Win%s sends base 0x%s - the label and the command "
            "disagree, which is how a bench operator records the wrong result"
            % (dec, hexbase))
    # and the channels the operator has to read must be published
    for ch in ("s5500Base", "s5500Idx", "s5500Snaps", "s5500Plaus"):
        assert ch in text, "%s is not published - the sweep is unreadable" % ch


def test_the_sweep_covers_the_whole_runtime_frame():
    """Seven 16-word windows over 118 words, with no gap wider than a window."""
    hdr = (ROOT / "firmware/targets/me711/hctarget.h").read_text(errors="replace")
    m = re.search(r"#define\s+TGT_ASIC_WORDS_RUN\s+(\d+)", hdr)
    assert m, "TGT_ASIC_WORDS_RUN not found"
    words = int(m.group(1))
    text = INI.read_text(errors="replace")
    bases = sorted(int(b) for b in
                   re.findall(r'cmdS5500Win(\d+)\s*=', text))
    assert bases[0] == 4, (
        "the sweep does not start at word 4, where the V9 hardware run PROVED "
        "the startup reply's analog block sits")
    for a, b in zip(bases, bases[1:]):
        assert b - a <= 16, "gap between window %d and %d exceeds one window" % (a, b)
    assert bases[-1] + 16 >= words - 16, (
        "the sweep stops at word %d and the frame is %d words - the tail is "
        "unreachable" % (bases[-1], words))
